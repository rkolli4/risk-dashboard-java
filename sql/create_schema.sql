CREATE TABLE market_snapshot (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR2(32) NOT NULL,
    price NUMBER(18, 4) NOT NULL,
    change_percent NUMBER(12, 6) NOT NULL,
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE risk_result (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    state VARCHAR2(16) NOT NULL,
    exposure NUMBER(18, 4) NOT NULL,
    utilization NUMBER(12, 6) NOT NULL,
    penalty NUMBER(18, 4) NOT NULL,
    message VARCHAR2(400) NOT NULL
);
